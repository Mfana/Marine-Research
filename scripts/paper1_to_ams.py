"""Build the AMS (Artificial Intelligence for the Earth Systems) submission of paper 1.

Source of truth: papers/paper1/main.tex (Elsevier version, numbers checked against results).
Output: papers/paper1/ams_submission/ — a flat folder ready for Editorial Manager:
  main.tex, ametsocV6.2.cls, ametsocV6.bst, references.bib, fig1.pdf ... figN.pdf
AMS rules applied: front matter before \\begin{document}; abstract <= 250 words; table
captions below tables; figure files without underscores or directory paths; tables inlined;
\\acknowledgments and \\availstatement; ametsocV6 bibliography style.

Usage:  .venv/bin/python scripts/paper1_to_ams.py <path-to-unzipped-AMS-package>
"""

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "papers/paper1"
OUT = SRC / "ams_submission"

# Manuscript text (title, abstract, significance statement) lives with the private manuscript
# sources in papers/paper1/, not in this public script.
TITLE = (SRC / "ams_title.txt").read_text().strip()
ABSTRACT = (SRC / "ams_abstract.tex").read_text().strip()
SIGNIFICANCE = (SRC / "ams_significance.tex").read_text().strip()
AUTHORS = (SRC / "ams_authors.tex").read_text().strip()
BACKMATTER = (SRC / "ams_backmatter.tex").read_text().strip()


def inline_tables(body: str) -> str:
    """Replace each table float with an inlined tabular and the caption moved below it."""
    pat = re.compile(
        r"\\begin\{table\}\[t\]\s*\\centering\s*\\caption\{(?P<cap>.*?)\}\s*\\label\{(?P<lab>[^}]*)\}\s*"
        r"\\small\s*(?P<inp>\\resizebox\{\\textwidth\}\{!\}\{\\input\{(?P<f1>[^}]*)\}\}|\\input\{(?P<f2>[^}]*)\})\s*"
        r"\\end\{table\}", re.S)

    def rep(m):
        f = m.group("f1") or m.group("f2")
        tab = (SRC / f).read_text().strip()
        if m.group("f1"):
            tab = "\\resizebox{\\textwidth}{!}{%\n" + tab + "}"
        return ("\\begin{table}[t]\n\\centering\n\\small\n" + tab + "\n"
                f"\\caption{{{m.group('cap')}}}\\label{{{m.group('lab')}}}\n\\end{{table}}")

    out, n = pat.subn(rep, body)
    if "\\input{tables/" in out:
        raise ValueError("a table was not converted")
    return out


def rename_figures(body: str) -> tuple[str, list[tuple[str, str]]]:
    names = []
    def rep(m):
        src = m.group(2)
        if src not in [s for s, _ in names]:
            names.append((src, f"fig{len(names) + 1}.pdf"))
        new = dict(names)[src]
        return f"\\includegraphics[{m.group(1)}]{{{new}}}"
    body = re.sub(r"\\includegraphics\[([^\]]*)\]\{([^}]*)\}", rep, body)
    return body, names


def convert_refs(body: str) -> str:
    """cleveref -> AMS style ("Fig. 1", "Table 2", "section 3")."""
    kind = {"fig": "Fig.", "tab": "Table", "sec": "section"}
    plural = {"fig": "Figs.", "tab": "Tables", "sec": "sections"}

    def one(lab):
        return lab.split(":")[0]

    def rep(m):
        cap = m.group(1) == "C"
        labs = [l.strip() for l in m.group(2).split(",")]
        kinds = [one(l) for l in labs]
        if len(set(kinds)) == 1 and len(labs) > 1:
            k = kinds[0]
            word = plural[k]
            refs = " and ".join("\\ref{%s}" % l for l in labs)
            s = f"{word}~{refs}"
        else:
            parts = [f"{kind[one(l)]}~\\ref{{{l}}}" for l in labs]
            s = " and ".join(parts)
        if cap and s[0].islower():
            s = s[0].upper() + s[1:]
        return s

    return re.sub(r"\\([cC])ref\{([^}]*)\}", rep, body)


def main(ams_dir: str) -> None:
    ams = Path(ams_dir)
    src = (SRC / "main.tex").read_text()
    start = src.index("\\section{Introduction}")
    end = src.index("\\section*{Code and data availability}")
    body = src[start:end]
    body = re.sub(r"%% -+\n", "", body)
    # Expand generated result prose before table inlining; retain generated numeric
    # macros in the AMS preamble so both manuscripts use the same results.
    body = re.sub(r"\\input\{tables/(results_[^}]+\.tex)\}",
                  lambda m: (SRC/"tables"/m.group(1)).read_text().strip(), body)
    body = inline_tables(body)
    body, figs = rename_figures(body)
    body = convert_refs(body)
    # AMS house style: "random forest" lower case in running text is fine either way; keep source wording.

    words = len(re.sub(r"\$[^$]*\$|\\[a-zA-Z]+|[{}]", " ", ABSTRACT).split())
    sig_words = len(SIGNIFICANCE.split())
    assert words <= 250, f"abstract has {words} words"
    assert sig_words <= 120, f"significance statement has {sig_words} words"

    tex = rf"""%% AMS submission of paper 1, generated by scripts/paper1_to_ams.py from papers/paper1/main.tex.
\documentclass{{ametsocV6.2}}

\usepackage{{booktabs}}
\usepackage{{siunitx}}
\usepackage{{url,placeins}}
\providecommand{{\nolinkurl}}{{\url}}
\sisetup{{detect-all}}
\emergencystretch=2em
{(SRC / 'tables/result_numbers.tex').read_text()}

\title{{{TITLE}}}

{AUTHORS}

\abstract{{{ABSTRACT}}}

\begin{{document}}

\maketitle

\sigstatement{{{SIGNIFICANCE}}}

{body.strip()}

\clearpage
{BACKMATTER}

\clearpage
\bibliographystyle{{ametsocV6}}
\bibliography{{references}}

\end{{document}}
"""
    # Update the existing package without deleting unrelated author files.
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "main.tex").write_text(tex)
    shutil.copy(ams / "ametsocV6.2.cls", OUT)
    shutil.copy(ams / "ametsocV6.bst", OUT)
    shutil.copy(ROOT / "papers/references.bib", OUT / "references.bib")
    for old, new in figs:
        shutil.copy(SRC / "figures" / old, OUT / new)
    print(f"abstract {words} words; significance {sig_words} words")
    print("figures:", ", ".join(f"{o} -> {n}" for o, n in figs))


if __name__ == "__main__":
    main(sys.argv[1])
